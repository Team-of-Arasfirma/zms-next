test("SEO Control Center: real fields, diagnostics, Blog synchronization, revisions and retained reset", async () => {
  const originals = [];
  const patch = (object, key, value) => { originals.push(() => { object[key] = value; }); object[key] = value; };
  const previousSecret = process.env.JWT_SECRET;
  process.env.JWT_SECRET = "seo-test-only-secret";
  let role = "superAdmin";
  let blogPermission = true;
  let seoEdit = true;
  let ticks = 0;
  const stamp = () => new Date(1700000000000 + (++ticks) * 1000);
  const records = new Map();
  const blog = { _id: "507f1f77bcf86cd799439016", title: "Article", slug: "article", category: "News", categorySlug: "news", subCategory: "Steel Structures", subCategorySlug: "steel", metaTitle: "Existing Blog SEO", metaDescription: "Existing Blog description", updatedAt: stamp(), content: "Preserved content" };
  const fixtures = new Map([
    [Product, [{ _id: "507f1f77bcf86cd799439012", name: "Legacy", status: "Active" }, { _id: "507f1f77bcf86cd799439013", name: "Panel", slug: "panel", status: "Active", category: "507f1f77bcf86cd799439014" }]],
    [Category, [{ _id: "507f1f77bcf86cd799439014", name: "Steel", slug: "steel" }]], [Blog, [blog]],
    [Career, [{ _id: "507f1f77bcf86cd799439015", jobTitle: "Engineer" }]],
  ]);
  const query = value => ({ select() { return this; }, lean: async () => value });
  const matches = (value, filter) => Object.entries(filter).every(([key, expected]) => expected?.$exists === false ? value[key] === undefined : expected instanceof Date ? +new Date(value[key]) === +expected : value[key] === expected);
  patch(Admin, "findById", async () => ({ _id: "507f1f77bcf86cd799439011", role, permissions: { seo: { view: true, edit: seoEdit, delete: true }, blogs: { edit: blogPermission } } }));
  for (const model of [Product, Category, Blog, Career]) patch(model, "find", () => query(fixtures.get(model)));
  patch(PageSeo, "find", () => query([...records.values()]));
  patch(PageSeo, "findById", path => query(records.get(path) || null));
  patch(PageSeo, "create", async value => { if (records.has(value._id)) throw Object.assign(new Error("duplicate"), { code: 11000 }); const result = { ...value, updatedAt: stamp() }; records.set(value._id, result); return result; });
  patch(PageSeo, "findOneAndUpdate", async (filter, update) => { const value = records.get(filter._id); if (!value || !matches(value, filter)) return null; const result = { ...value, ...update.$set, updatedAt: stamp() }; records.set(value._id, result); return result; });
  patch(Blog, "findById", () => query({ ...blog }));
  patch(Blog, "findOneAndUpdate", async (filter, update) => { if (!matches(blog, filter)) return null; Object.assign(blog, update.$set, { updatedAt: stamp() }); return { ...blog }; });
  const app = express(); app.use(express.json()); app.use("/api/seo", publicSeoRouter); app.use("/api/admin/seo", adminSeoRouter);
  const server = app.listen(0, "127.0.0.1"); await new Promise(resolve => server.once("listening", resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const token = jwt.sign({ id: "507f1f77bcf86cd799439011" }, process.env.JWT_SECRET);
  const req = (url, options = {}) => fetch(base + url, { ...options, headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}`, ...options.headers } });
  const get = async path => (await req(`/api/admin/seo?path=${encodeURIComponent(path)}`)).json();
  const save = (item, title, extra = {}) => req(`/api/admin/seo?path=${encodeURIComponent(item.pagePath)}`, { method: "PUT", body: JSON.stringify({ pageKey: item.pagePath, pagePath: item.pagePath, contentId: item.contentId, revision: item.revision, seoTitle: title, metaDescription: "Description", ...extra }) });
  try {
    assert.equal((await req("/api/admin/seo/pages", { headers: { Authorization: "" } })).status, 401);
    role = "staff"; blogPermission = false;
    seoEdit = false; assert.equal((await save(await get("/about"), "Denied SEO edit")).status, 403); seoEdit = true;
    const blogItem = await get("/news/steel/article");
    assert.equal(blogItem.seoTitle, "Existing Blog SEO");
    assert.equal(blogItem.metaDescription, "Existing Blog description");
    assert.equal((await save(blogItem, "Denied")).status, 405);
    role = "superAdmin";
    const pages = await (await req("/api/admin/seo/pages")).json();
    for (const path of ["/", "/about", "/product/panel", "/product/item-507f1f77bcf86cd799439012", "/product/category/steel", "/news/steel/article", "/blog/category/news", "/blog/category/news/steel"]) assert.ok(pages.some(p => p.pagePath === path), path);
    assert.deepEqual(new Set(pages.map(item => item.tab)), new Set(["Pages", "Products", "Product Categories", "Blog Posts", "Blog Categories", "Blog Subcategories"]));
    assert.ok(!pages.some(item => item.pagePath.startsWith("/career/apply/")));
    assert.equal(new Set(pages.map(item => item.pagePath)).size, pages.length);
    assert.equal(blogItem.readOnly, true);
    assert.equal(blogItem.blogAdminUrl, `/admin/blogs?edit=${blog._id}`);
    assert.equal(blogItem.seoUpdatedAt, null, "General Blog updatedAt is not an SEO update date");
    const categoryItem = await get("/blog/category/news");
    const subcategoryItem = await get("/blog/category/news/steel");
    assert.equal(categoryItem.label, "News");
    assert.equal(subcategoryItem.label, "News / Steel Structures");
    const about = await get("/about");
    assert.notEqual(about.status, "Missing Metadata");
    assert.equal((await save(about, "About title")).status, 200);
    assert.equal((await save(about, "Stale write")).status, 409);
    assert.equal((await save(await get("/contact"), "Contact title")).status, 200);
    assert.equal((await save(await get("/about"), "Updated title")).status, 200);
    assert.equal(records.size, 2);
    assert.equal((await get("/about")).seoTitle, "Updated title");
    assert.deepEqual(Object.keys(await (await req("/api/seo?path=/about")).json()).sort(), ["metaDescription", "seoTitle"]);
    assert.equal((await save({ pagePath: "/admin", revision: "none" }, "Invalid")).status, 400);
    assert.equal((await req("/api/seo?path=https://example.com")).status, 400);
    assert.equal((await save(await get("/about"), "x".repeat(301))).status, 400);
    assert.equal((await save(blogItem, "Synchronized Blog SEO")).status, 405);
    assert.equal(blog.metaTitle, "Existing Blog SEO");
    assert.equal(blog.content, "Preserved content");
    assert.equal(records.size, 2, "Blog saves never create PageSeo records");
    assert.equal((await save(blogItem, "Stale Blog draft")).status, 405);
    blog.metaTitle = "Edited in Blog Admin"; blog.updatedAt = stamp();
    assert.equal((await get(blogItem.pagePath)).seoTitle, "Edited in Blog Admin");
    records.set(blogItem.pagePath, { _id: blogItem.pagePath, seoTitle: "Legacy title", metaDescription: "Legacy description", updatedAt: stamp() });
    let freshBlog = await get(blogItem.pagePath);
    assert.equal(freshBlog.effectiveTitle, "Edited in Blog Admin | ZMSIPL");
    assert.equal(freshBlog.seoTitle, "Edited in Blog Admin");
    assert.equal(freshBlog.status, "Needs Review");
    assert.equal((await req(`/api/admin/seo?path=${encodeURIComponent(blogItem.pagePath)}`, { method: "DELETE", body: JSON.stringify({ revision: freshBlog.revision }) })).status, 400);
    const legacy = freshBlog.legacyOverrides[0];
    const resolution = await req(`/api/admin/seo/legacy?path=${encodeURIComponent(blogItem.pagePath)}`, { method: "PATCH", body: JSON.stringify({ contentId: blogItem.contentId, legacyPath: legacy.pagePath, revision: legacy.revision }) });
    assert.equal(resolution.status, 200);
    assert.equal(records.get(blogItem.pagePath).seoTitle, "Legacy title", "Legacy data is retained");
    assert.equal(records.get(blogItem.pagePath).disabled, true);
    assert.deepEqual(await (await req(`/api/seo?path=${encodeURIComponent(blogItem.pagePath)}`)).json(), {});
    freshBlog = await get(blogItem.pagePath);
    assert.equal(freshBlog.effectiveTitle, "Edited in Blog Admin | ZMSIPL");
    const beforeReset = await get("/about");
    assert.equal((await req("/api/admin/seo?path=/about", { method: "DELETE", body: JSON.stringify({ revision: beforeReset.revision }) })).status, 200);
    assert.equal(records.get("/about").seoTitle, "Updated title");
    assert.deepEqual(await (await req("/api/seo?path=/about")).json(), {});
    assert.equal((await get("/about")).hasOverride, false);
    const beforeCategorySave = blog.metaTitle;
    assert.equal((await save(categoryItem, "Independent category SEO")).status, 200);
    assert.equal((await save(subcategoryItem, "Independent subcategory SEO")).status, 200);
    assert.equal((await get(categoryItem.pagePath)).seoTitle, "Independent category SEO");
    assert.equal((await get(subcategoryItem.pagePath)).seoTitle, "Independent subcategory SEO");
    assert.ok((await get(categoryItem.pagePath)).seoUpdatedAt);
    assert.equal(blog.metaTitle, beforeCategorySave);
    const categorySnapshot = await get(categoryItem.pagePath);
    assert.equal((await req(`/api/admin/seo?path=${encodeURIComponent(categoryItem.pagePath)}`, { method: "DELETE", body: JSON.stringify({ revision: categorySnapshot.revision }) })).status, 200);
    assert.equal((await get(categoryItem.pagePath)).hasOverride, false);
    assert.equal((await get(subcategoryItem.pagePath)).seoTitle, "Independent subcategory SEO");
    assert.equal(records.get(categoryItem.pagePath).seoTitle, "Independent category SEO");
    assert.equal(blog.metaTitle, beforeCategorySave);
    blog.slug = "renamed";
    assert.equal((await save(freshBlog, "Old URL save")).status, 400);
    records.set("/old-url", { _id: "/old-url", seoTitle: "Retained" });
    const envelope = await (await req("/api/admin/seo/pages?details=1")).json();
    assert.equal(typeof envelope.asOf, "number");
    assert.ok(envelope.retainedOverrides.some(item => item.pagePath === "/old-url"));
    assert.equal(validSeoPath("//evil.com"), false);
  } finally {
    server.closeAllConnections(); await new Promise(resolve => server.close(resolve));
    originals.reverse().forEach(restore => restore());
    if (previousSecret === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = previousSecret;
  }
});

test("server metadata preserves fallback, canonical, social images and robots", async () => {
  const source = await readFile(new URL("../../frontend/lib/pageSeo.js", import.meta.url), "utf8");
  const { withPageSeo } = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
  const original = globalThis.fetch;
  const fallback = { title: "Original", description: "Original description", alternates: { canonical: "/product/example" }, openGraph: { images: [{ url: "https://example.com/a.jpg" }], type: "website" }, twitter: { card: "summary_large_image" }, robots: { index: false } };
  try {
    globalThis.fetch = async () => ({ ok: true, json: async () => ({}) });
    assert.equal(await withPageSeo("/", fallback), fallback);
    globalThis.fetch = async () => { throw new Error("offline"); };
    assert.equal(await withPageSeo("/", fallback), fallback);
    globalThis.fetch = async () => ({ ok: false });
    assert.equal(await withPageSeo("/", fallback), fallback);
    globalThis.fetch = async () => ({ ok: true, json: async () => ({ seoTitle: "Exact saved title", metaDescription: "Saved description" }) });
    const result = await withPageSeo("/product/example", fallback);
    assert.deepEqual(result.title, { absolute: "Exact saved title" });
    assert.equal(result.description, "Saved description");
    assert.equal(result.alternates, fallback.alternates);
    assert.equal(result.openGraph.images, fallback.openGraph.images);
    assert.equal(result.openGraph.title, "Exact saved title");
    assert.equal(result.twitter.card, "summary_large_image");
    assert.equal(result.robots.index, false);
    globalThis.fetch = async () => ({ ok: true, json: async () => ({ seoTitle: "", metaDescription: "Only description" }) });
    assert.equal((await withPageSeo("/", fallback)).title, "Original");
  } finally { globalThis.fetch = original; }
});
